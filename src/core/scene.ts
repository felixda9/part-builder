import { z } from 'zod';
import type { Mat3, Vec3 } from './math';

export const SHAPES = ['Block', 'Wedge', 'CornerWedge'] as const;
export const MATERIALS = ['Plastic', 'SmoothPlastic', 'Neon'] as const;
export const SURFACES = ['Studs', 'Inlet', 'Smooth'] as const;
/** Roblox NormalId faces: Top +Y, Bottom -Y, Front -Z, Back +Z, Right +X, Left -X. */
export const FACES = ['top', 'bottom', 'front', 'back', 'left', 'right'] as const;

export type Shape = (typeof SHAPES)[number];
export type Material = (typeof MATERIALS)[number];
export type Surface = (typeof SURFACES)[number];
export type Face = (typeof FACES)[number];
export type Surfaces = Record<Face, Surface>;

export const zVec3 = z.tuple([z.number(), z.number(), z.number()]);
export const zMat3 = z.tuple([
  z.number(), z.number(), z.number(),
  z.number(), z.number(), z.number(),
  z.number(), z.number(), z.number(),
]);
export const zColor = z.string().regex(/^#[0-9a-fA-F]{6}$/, 'color must be #RRGGBB');
export const zShape = z.enum(SHAPES);
export const zMaterial = z.enum(MATERIALS);
export const zSurface = z.enum(SURFACES);
export const zSurfaces = z.object({
  top: zSurface, bottom: zSurface, front: zSurface, back: zSurface, left: zSurface, right: zSurface,
});

export const zPart = z.object({
  id: z.string(),
  name: z.string().min(1),
  shape: zShape,
  size: zVec3,
  position: zVec3,
  rotation: zMat3,
  color: zColor,
  material: zMaterial,
  surfaces: zSurfaces,
  group: z.string().nullable(),
  transparency: z.number().min(0).max(1).default(0),
  /** Set on parts generated by a linked mirror group; regenerated after every edit. */
  mirrorOf: z.string().nullable().default(null),
});

export const zGroup = z.object({
  id: z.string(),
  name: z.string().min(1),
  parent: z.string().nullable(),
  pivot: zVec3,
  mainPart: z.string().nullable(),
  /** Linked mirror: this group's parts are regenerated by reflecting group `mirrorOf` across X. */
  mirrorOf: z.string().nullable().default(null),
});

export const zScene = z.object({
  version: z.literal(1),
  name: z.string(),
  snap: z.number().default(0.05),
  parts: z.array(zPart),
  groups: z.array(zGroup),
  palette: z.array(zColor).default([]),
  nextId: z.number().int().default(1),
});

export type Part = z.infer<typeof zPart> & { size: Vec3; position: Vec3; rotation: Mat3 };
export type Group = z.infer<typeof zGroup> & { pivot: Vec3 };
export type SceneDoc = Omit<z.infer<typeof zScene>, 'parts' | 'groups'> & { parts: Part[]; groups: Group[] };

export function emptyScene(name = 'Model'): SceneDoc {
  return { version: 1, name, snap: 0.05, parts: [], groups: [], palette: [], nextId: 1 };
}

export const ALL_STUDS: Surfaces = { top: 'Studs', bottom: 'Studs', front: 'Studs', back: 'Studs', left: 'Studs', right: 'Studs' };
export const ALL_SMOOTH: Surfaces = { top: 'Smooth', bottom: 'Smooth', front: 'Smooth', back: 'Smooth', left: 'Smooth', right: 'Smooth' };

/**
 * Default look: smooth Plastic, no studs (studs only when asked for). Small detail parts
 * (largest side under 1 stud: eyes, rivets, trim) are SmoothPlastic.
 */
export function defaultLook(size: Vec3): { material: Material; surfaces: Surfaces } {
  return { material: Math.max(...size) < 1 ? 'SmoothPlastic' : 'Plastic', surfaces: { ...ALL_SMOOTH } };
}

export const clone = <T>(v: T): T => structuredClone(v);

export function parseScene(raw: unknown): SceneDoc {
  return zScene.parse(raw) as SceneDoc;
}
