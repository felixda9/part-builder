// Luau builder script: one generic builder + compact per-part data. Run it through Roblox
// Studio's MCP (execute_luau, Edit datamodel) to push the model into the open place. Wrapped in
// ChangeHistoryService so it can be undone in Studio.

import { type CFrame, type Vec3, IDENTITY } from '../math';
import type { SceneDoc } from '../scene';
import { type RigPlan, planRig } from './rig';

const n = (v: number) => {
  const r = Math.round(v * 1e4) / 1e4;
  return String(Object.is(r, -0) ? 0 : r);
};
const q = (s: string) => JSON.stringify(s); // JSON string escaping is valid Luau
const isIdentity = (c: CFrame) => c.R.every((v, i) => Math.abs(v - IDENTITY[i]) < 1e-9);
const cfArgs = (c: CFrame) => `{${[...c.p, ...(isIdentity(c) ? [] : c.R)].map(n).join(',')}}`;
const SH = { Part: 'B', WedgePart: 'W', CornerWedgePart: 'C' } as const;
const MAT = { Plastic: 'P', SmoothPlastic: 'S', Neon: 'N' } as const;
const SU = { Studs: 'S', Inlet: 'I', Smooth: 'M' } as const;

export function toLuau(scene: SceneDoc, opts: { rig: boolean; offset?: Vec3; name?: string; replace?: boolean }): { code: string; plan: RigPlan } {
  const plan = planRig(scene, opts);
  const index = new Map(plan.parts.map((p, i) => [p.key, i + 1]));
  const P = plan.parts.map((e) => {
    const p = e.part;
    const s = p?.surfaces;
    const surf = s ? [s.top, s.bottom, s.front, s.back, s.left, s.right].map((x) => SU[x]).join('') : 'MMMMMM';
    return `{${q(e.name)},"${SH[e.className]}",${e.size.map(n).join(',')},${cfArgs(e.cframe)},"${(p?.color ?? '#a3a2a5').slice(1)}","${MAT[p?.material ?? 'SmoothPlastic']}","${surf}",${n(e.transparency)},${e.anchored ? 1 : 0},${e.canCollide ? 1 : 0}}`;
  });
  const J = plan.motors.map((j) => `{${q(j.name)},${index.get(j.part0)},${index.get(j.part1)},${cfArgs(j.c0)},${cfArgs(j.c1)}}`);
  const W = plan.welds.map((j) => `{${index.get(j.part0)},${index.get(j.part1)},${cfArgs(j.c0)}}`);
  const name = opts.name ?? scene.name;

  const code = `-- Generated by part-builder. Builds "${name}" (${plan.parts.length} parts) in Workspace.
local NAME, REPLACE, RIG = ${q(name)}, ${opts.replace === false ? 'false' : 'true'}, ${plan.rigged ? 'true' : 'false'}
local P = {
${P.join(',\n')}
}
local J = {${J.join(',')}}
local W = {${W.join(',')}}
local PRIMARY = ${index.get(plan.primary)}

local CHS = game:GetService("ChangeHistoryService")
local rec = CHS:TryBeginRecording("Insert " .. NAME)
local SH = {B = "Part", W = "WedgePart", C = "CornerWedgePart"}
local MAT = {P = Enum.Material.Plastic, S = Enum.Material.SmoothPlastic, N = Enum.Material.Neon}
local SU = {S = Enum.SurfaceType.Studs, I = Enum.SurfaceType.Inlet, M = Enum.SurfaceType.Smooth}
local function cfr(t)
	if #t == 3 then return CFrame.new(t[1], t[2], t[3]) end
	return CFrame.new(table.unpack(t))
end
local ok, err = pcall(function()
	if REPLACE then
		local old = workspace:FindFirstChild(NAME)
		if old then old:Destroy() end
	end
	local model = Instance.new("Model")
	model.Name = NAME
	local parts = {}
	for i, d in ipairs(P) do
		local p = Instance.new(SH[d[2]])
		p.Name = d[1]
		p.Size = Vector3.new(d[3], d[4], d[5])
		p.CFrame = cfr(d[6])
		p.Color = Color3.fromHex(d[7])
		p.Material = MAT[d[8]]
		local s = d[9]
		p.TopSurface = SU[s:sub(1, 1)]; p.BottomSurface = SU[s:sub(2, 2)]
		p.FrontSurface = SU[s:sub(3, 3)]; p.BackSurface = SU[s:sub(4, 4)]
		p.LeftSurface = SU[s:sub(5, 5)]; p.RightSurface = SU[s:sub(6, 6)]
		p.Transparency = d[10]
		p.Anchored = d[11] == 1
		p.CanCollide = d[12] == 1
		p.Parent = model
		parts[i] = p
	end
	for _, j in ipairs(J) do
		local m = Instance.new("Motor6D")
		m.Name = j[1]; m.Part0 = parts[j[2]]; m.Part1 = parts[j[3]]
		m.C0 = cfr(j[4]); m.C1 = cfr(j[5])
		m.Parent = parts[j[2]]
	end
	for _, w in ipairs(W) do
		local x = Instance.new("Weld")
		x.Name = parts[w[2]].Name .. "_Weld"
		x.Part0 = parts[w[1]]; x.Part1 = parts[w[2]]
		x.C0 = cfr(w[3])
		x.Parent = parts[w[2]]
	end
	if RIG then
		local ac = Instance.new("AnimationController")
		Instance.new("Animator").Parent = ac
		ac.Parent = model
	end
	model.PrimaryPart = parts[PRIMARY]
	model.Parent = workspace
	print(("built %s: %d parts, %d motors, %d welds"):format(NAME, #P, #J, #W))
end)
if rec then CHS:FinishRecording(rec, ok and Enum.FinishRecordingOperation.Commit or Enum.FinishRecordingOperation.Cancel) end
if not ok then error(err) end
`;
  return { code, plan };
}
